import unreal, os
SDIR='E:/projects/AlienSkies/Screenshots'
ues=unreal.get_editor_subsystem(unreal.UnrealEditorSubsystem)
w=ues.get_editor_world()
unreal.SystemLibrary.execute_console_command(w,'Slate.bAllowThrottling 0')
loc,rot=ues.get_level_viewport_camera_info()
rt=unreal.TextureRenderTarget2D(); rt.set_editor_property('size_x',1280); rt.set_editor_property('size_y',720)
rt.set_editor_property('render_target_format',unreal.TextureRenderTargetFormat.RTF_RGBA8_SRGB)
eas=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
ca=eas.spawn_actor_from_class(unreal.SceneCapture2D,loc,rot)
cap=ca.capture_component2d
cap.set_editor_property('texture_target',rt)
cap.set_editor_property('capture_source',unreal.SceneCaptureSource.SCS_FINAL_COLOR_LDR)
cap.set_editor_property('fov_angle',90.0)
cap.set_editor_property('post_process_blend_weight',1.0)
mat=unreal.load_asset('/Game/AlienSkies/Materials/M_PPLensing')
# direct assignment (like PPV)
s=cap.get_editor_property('post_process_settings')
wb=unreal.WeightedBlendable(); wb.set_editor_property('weight',1.0); wb.set_editor_property('object',mat)
wbs=unreal.WeightedBlendables(); wbs.set_editor_property('array',[wb])
s.set_editor_property('weighted_blendables',wbs)
cap.set_editor_property('post_process_settings',s)
# read back
s2=cap.get_editor_property('post_process_settings')
cnt=len(list(s2.get_editor_property('weighted_blendables').get_editor_property('array')))
print('blendable count on capture after assign:',cnt)
cap.capture_scene()
unreal.RenderingLibrary.export_render_target(w,rt,SDIR,'iter.png')
eas.destroy_actor(ca)
print('captured')
